with open(r"D:\studies\DATA_WAREHOUSING\lab\exp\exp12.r", "w", encoding="utf-8") as f:
    f.write("# Construct a Q-Q plot for 21,24,27,29,31,34,37,41,45,48 and comment on normality.\n")
    f.write("\n")
    f.write("data <- c(21, 24, 27, 29, 31, 34, 37, 41, 45, 48)\n")
    f.write("\n")
    f.write("cat(\"Data:\", data, \"\\n\\n\")\n")
    f.write("\n")
    f.write("sw_test <- shapiro.test(data)\n")
    f.write("cat(\"Shapiro-Wilk Normality Test:\\n\")\n")
    f.write("cat(\"  W-statistic:\", sw_test$statistic, \"\\n\")\n")
    f.write("cat(\"  p-value    :\", sw_test$p.value, \"\\n\\n\")\n")
    f.write("\n")
    f.write("if (sw_test$p.value > 0.05) {\n")
    f.write("  cat(\"Comment: p-value > 0.05 => Data appears NORMALLY DISTRIBUTED.\\n\")\n")
    f.write("} else {\n")
    f.write("  cat(\"Comment: p-value <= 0.05 => Data does NOT appear normally distributed.\\n\")\n")
    f.write("}\n")
    f.write("\n")
    f.write("qqnorm(data, main = \"Q-Q Plot for Normality Check\", col = \"blue\", pch = 19)\n")
    f.write("qqline(data, col = \"red\", lwd = 2)\n")
print("Done")

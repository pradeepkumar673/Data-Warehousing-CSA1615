# Demonstrate vector addition, subtraction, multiplication and division on two numeric vectors.

v1 <- c(10, 20, 30, 40, 50)
v2 <- c(5, 4, 3, 2, 1)

cat("Vector 1:", v1, "\n")
cat("Vector 2:", v2, "\n")
cat("Addition:", v1 + v2, "\n")
cat("Subtraction:", v1 - v2, "\n")
cat("Multiplication:", v1 * v2, "\n")
cat("Division:", v1 / v2, "\n")

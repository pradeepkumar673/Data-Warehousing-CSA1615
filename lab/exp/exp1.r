# Create 10 student marks and calculate mean, median, variance and standard deviation.

marks <- c(72, 85, 90, 65, 78, 88, 95, 60, 74, 82)

cat("Student Marks:", marks, "\n\n")
cat("Mean      :", mean(marks), "\n")
cat("Median    :", median(marks), "\n")
cat("Variance  :", var(marks), "\n")
cat("Std Dev   :", sd(marks), "\n")
